<?php

namespace App\Models\Projects;

use App\Models\Boq\ProjectBudgetLine;
use App\Models\Concerns\Auditable;
use App\Models\Concerns\BelongsToCompany;
use App\Models\Concerns\Blameable;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

/**
 * Company WBS / Project Cost Head for Cost Control dashboards.
 * Distinct from operational CostHead (material/labour/equipment/…).
 */
#[Fillable(['parent_id', 'code', 'name', 'sort_order', 'is_system', 'is_active'])]
class ProjectCostHead extends Model
{
    use Auditable, BelongsToCompany, Blameable;

    protected function casts(): array
    {
        return [
            'sort_order' => 'integer',
            'is_system' => 'boolean',
            'is_active' => 'boolean',
        ];
    }

    public function parent(): BelongsTo
    {
        return $this->belongsTo(self::class, 'parent_id');
    }

    public function children(): HasMany
    {
        return $this->hasMany(self::class, 'parent_id');
    }

    /**
     * @param  Builder<static>  $query
     * @return Builder<static>
     */
    public function scopeActive(Builder $query): Builder
    {
        return $query->where('is_active', true);
    }

    /**
     * @param  Builder<static>  $query
     * @return Builder<static>
     */
    public function scopeOrdered(Builder $query): Builder
    {
        return $query->orderBy('sort_order')->orderBy('id');
    }

    public function budgetLines(): HasMany
    {
        return $this->hasMany(ProjectBudgetLine::class);
    }
}
